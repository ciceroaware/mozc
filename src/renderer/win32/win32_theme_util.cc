#include "renderer/win32/win32_theme_util.h"

#include <windows.h>

namespace mozc {
namespace renderer {
namespace win32 {

bool IsAppsUseLightTheme() {
  DWORD value = 1;
  DWORD value_size = sizeof(value);
  const LONG result = ::RegGetValueW(
      HKEY_CURRENT_USER,
      L"Software\\Microsoft\\Windows\\CurrentVersion\\Themes\\Personalize",
      L"AppsUseLightTheme", RRF_RT_REG_DWORD, nullptr, &value, &value_size);
  if (result != ERROR_SUCCESS) {
    return true;
  }
  return value != 0;
}

}  // namespace win32
}  // namespace renderer
}  // namespace mozc
